import test from 'node:test';
import assert from 'node:assert/strict';
import {validateIsolation,readIsolationInputs} from '../scripts/assert-isolation.mjs';
const original=readIsolationInputs();
const mutate=(key,fn)=>({...original,[key]:fn(original[key])});
const deny=(candidate)=>assert.ok(validateIsolation(candidate).length>0);
test('baseline local isolation is valid',()=>assert.deepEqual(validateIsolation(original),[]));
test('reject public workers_dev',()=>deny(mutate('config',s=>s.replace('workers_dev = false','workers_dev = true'))));
test('reject real D1 database id',()=>deny(mutate('config',s=>s.replace('00000000-0000-0000-0000-000000000030','aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa'))));
test('reject route addition',()=>deny(mutate('config',s=>s+'\nroute = "example.com/*"')));
test('reject account ID addition',()=>deny(mutate('config',s=>s+'\naccount_id = "real-account"')));
test('reject removal of local D1 flag',()=>deny(mutate('smoke',s=>s.replace('execute ASSESSMENT_DB --local','execute ASSESSMENT_DB'))));
test('reject remote D1',()=>deny(mutate('smoke',s=>s.replace('execute ASSESSMENT_DB --local','execute ASSESSMENT_DB --remote'))));
test('reject deploy command',()=>deny(mutate('smoke',s=>s+'\nnpx wrangler deploy')));
test('reject public bind',()=>deny(mutate('smoke',s=>s.replace('--ip 127.0.0.1','--ip 0.0.0.0'))));
test('reject Cloudflare deploy action',()=>deny(mutate('localCI',s=>s+'\n- uses: cloudflare/wrangler-action@v3')));
test('reject Cloudflare credential injection',()=>deny(mutate('localCI',s=>s+'\nCLOUDFLARE_API_TOKEN: bad')));
test('reject branch scope change',()=>deny(mutate('localCI',s=>s.replace('jaguar/v30-3-recovery-archive','main'))));
test('reject write permission',()=>deny(mutate('localCI',s=>s.replace('contents: read','contents: write'))));
test('reject disabled denylist guard',()=>deny(mutate('worker',s=>s.replace('includes(url.pathname)','includes("none")'))));
test('reject replacing blocked-route HTTP 404',()=>deny(mutate('worker',s=>s.replaceAll("return Response.json({error: 'route_disabled'}, {status: 404});","return Response.json({ok: true}, {status: 200});"))));
