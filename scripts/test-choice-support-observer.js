#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let clickHandler=null, observed=null, captures=0;
const target={dataset:{choiceAudio:'fresh-mild-cheese'}};
const context=Object.freeze({currentExperienceId:'shopping-for-dinner',experienceLanguage:'en',experienceQuestion:'Which cheese should we choose?',experienceChoiceCandidate:'fresh-mild-cheese'});
const sandbox=vm.createContext({document:{addEventListener(type,handler,capture){if(type==='click'&&capture===true)clickHandler=handler;}}});
sandbox.globalThis=sandbox;
vm.runInContext(fs.readFileSync('js/choice-support-sensor.js','utf8'),sandbox,{filename:'js/choice-support-sensor.js'});
sandbox.SIYAYOChoiceSupportSensor=sandbox.SIYAYOChoiceSupportSensor.create();
sandbox.SIYAYOVerbExplorerAdaptiveStateBridge={capture(){captures+=1;return context;}};
vm.runInContext(fs.readFileSync('js/verb-explorer-choice-support-observer.js','utf8'),sandbox,{filename:'js/verb-explorer-choice-support-observer.js'});
const observer=sandbox.SIYAYOVerbExplorerChoiceSupportObserver;
assert(observer&&typeof observer.install==='function');
assert.equal(observer.install({onObserved(value){observed=value;}}),true);
assert.equal(observer.install(),false,'observer installation must be idempotent');
assert.equal(typeof clickHandler,'function');
clickHandler({target:{closest(selector){return selector==='[data-choice-audio]'?target:null;}}});
assert.equal(captures,1);
assert(observed,'real choice-audio boundary should produce a grounded support observation');
assert.equal(observed.value,'audio');
assert.equal(observed.context.currentExperienceId,'shopping-for-dinner');
assert.equal(observed.context.experienceLanguage,'en');
assert.equal(observed.context.experienceQuestion,'Which cheese should we choose?');
assert.equal(observed.context.experienceChoiceCandidate,'fresh-mild-cheese');
assert.equal(Object.isFrozen(observed),true);
observed=null;
clickHandler({target:{closest(){return null;}}});
assert.equal(observed,null,'unrelated clicks must not create support observations');
assert.equal(captures,1,'unrelated clicks must not capture state');
assert.equal(sandbox.SIYAYOChoiceSupportSensor.support(Object.freeze({...context,experienceLanguage:'es'})),'none','audio support must not leak into another language context');
assert.equal(sandbox.SIYAYOChoiceSupportSensor.support(context),'audio');
console.log('Choice support observer: PASS — real choice-audio boundary records contextual audio support without leaking across E/L/Q/C.');
