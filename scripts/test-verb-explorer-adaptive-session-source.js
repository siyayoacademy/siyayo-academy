const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const AdaptiveEvidenceProfile=require('../js/adaptive-evidence-profile.js');
const AdaptiveAttemptLoop=require('../js/adaptive-attempt-loop.js');
const sourceCode=fs.readFileSync('js/verb-explorer-adaptive-session-source.js','utf8');
const sandbox={AdaptiveEvidenceProfile,AdaptiveAttemptLoop};
vm.createContext(sandbox);
vm.runInContext(sourceCode,sandbox);
const profile=AdaptiveEvidenceProfile.createProfile('learner-1');
const context={currentExperience:'shopping-for-dinner'};
const session=sandbox.SIYAYOVerbExplorerAdaptiveSessionSource.begin(profile,context);
assert.ok(session&&session.decision&&Array.isArray(session.trace));
assert.equal(session.decision.action,'continue-assessment');
assert.equal(session.decision.experienceId,'shopping-for-dinner');
assert.equal(session.decision.focus,'assessment');
assert.equal(session.trace[0].event,'experience-selected');
assert.equal(session.trace[0].experienceId,'shopping-for-dinner');
assert.equal(sandbox.SIYAYOVerbExplorerAdaptiveSessionSource.begin(null,context),null);
assert.equal(sandbox.SIYAYOVerbExplorerAdaptiveSessionSource.begin(profile,null),null);
console.log('Verb Explorer adaptive Session source: PASS — canonical AttemptLoop.begin creates S without manual decision mutation; missing Profile or Context preserves WAIT.');
