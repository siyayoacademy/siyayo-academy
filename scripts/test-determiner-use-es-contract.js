const assert = require('node:assert/strict');
const Local = require('../js/adaptive-determiner-use-probe-specification-source.js');
const Transfer = require('../js/adaptive-determiner-use-transfer-probe-specification-source.js');
const LocalResult = require('../js/adaptive-determiner-use-probe-result.js');
const TransferResult = require('../js/adaptive-determiner-use-transfer-probe-result.js');
const skills = require('../data/learning/skills/which.json');
const experiences = require('../data/learning/experience-seeds.json').items;
const nouns = require('../data/lexicon/nouns/nouns.json');
const shopping = experiences.find(item => item.id === 'shopping-for-dinner');
const preparing = experiences.find(item => item.id === 'preparing-dinner');
const local = Local.resolve(skills, shopping, 'es', nouns);
assert.ok(local);
assert.equal(local.prompt, '¿Qué ___ deberíamos elegir?');
assert.equal(local.expectedAlternativeId, 'cheese');
assert.deepEqual(local.alternatives.map(item => item.label), ['queso', 'deberíamos', 'elegir']);
const transfer = Transfer.resolve(skills, local, preparing, nouns, 'es');
assert.ok(transfer);
assert.equal(transfer.prompt, '¿Qué ___ deberíamos cocinar primero?');
assert.equal(transfer.expectedAlternativeId, 'carrots');
assert.deepEqual(transfer.alternatives.map(item => item.label), ['zanahorias', 'deberíamos', 'cocinar', 'primero']);
const localEvent = { observed:true, actor:'learner', source:'determiner-use-probe-select', occurrenceId:'es-local', choice:'cheese', experienceId:local.experienceId, dimension:local.dimension, targetForm:local.targetForm, targetNoun:local.targetNoun };
assert.equal(LocalResult.evaluate(local,localEvent).result, 'pass');
assert.equal(LocalResult.evaluate(local,{...localEvent,choice:'elegir'}).result, 'fail');
const transferEvent = { observed:true, actor:'learner', source:'determiner-use-transfer-probe-select', occurrenceId:'es-transfer', choice:'carrots', fromExperienceId:transfer.fromExperienceId, experienceId:transfer.experienceId, dimension:transfer.dimension, targetForm:transfer.targetForm, targetNoun:transfer.targetNoun, mode:'transfer' };
assert.equal(TransferResult.evaluate(transfer,transferEvent).result, 'pass');
assert.equal(TransferResult.evaluate(transfer,{...transferEvent,mode:undefined}),null);
assert.equal(Local.resolve(skills,shopping,'es'),null,'missing canonical noun translation fails closed');
assert.equal(Transfer.resolve(skills,local,shopping,nouns,'es'),null,'same Experience cannot claim transfer');
assert.equal(Transfer.resolve(skills,local,{...preparing, links:{...preparing.links,vocabulary:[]}},nouns,'es'),null,'target noun must belong to destination');
const portugueseLocal=Local.resolve(skills,shopping,'pt',nouns);
assert.equal(portugueseLocal.prompt,'Qual ___ devemos escolher?');
assert.deepEqual(portugueseLocal.alternatives.map(item=>item.label),['queijo','devemos','escolher']);
const portugueseTransfer=Transfer.resolve(skills,portugueseLocal,preparing,nouns,'pt');
assert.equal(portugueseTransfer.prompt,'Quais ___ devemos cozinhar primeiro?');
assert.deepEqual(portugueseTransfer.alternatives.map(item=>item.label),['cenouras','devemos','cozinhar','primeiro']);
assert.equal(LocalResult.evaluate(portugueseLocal,{...localEvent,choice:'cheese'}).result,'pass');
assert.equal(TransferResult.evaluate(portugueseTransfer,{...transferEvent,choice:'carrots'}).result,'pass');
assert.equal(Local.resolve(skills,shopping,'pt'),null,'PT without canonical lexicon fails closed');
assert.equal(Transfer.resolve(skills,portugueseLocal,{...preparing,thinkingMind:preparing.thinkingMind.map(entry=>entry.questionWord==='which'?{...entry,questionWordLabel:{...entry.questionWordLabel,pt:'QUAL'}}:entry)},nouns,'pt'),null,'plural form must agree with authored destination');
console.log('Spanish and Portuguese local and transfer WHICH specifications: PASS');
