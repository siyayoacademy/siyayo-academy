#!/usr/bin/env node
'use strict';
// Run from the root of siyayoacademy/siyayo-academy after applying the CSS.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const css = fs.readFileSync('css/verb-explorer.css','utf8');
const comparison = fs.readFileSync('js/verb-explorer-pronoun-comparison.js','utf8');
const headWire = fs.readFileSync('js/adaptive-dependency-head-probe-browser-wire.js','utf8');
const marker = 'JAGUAR ELO 7D.3.2';
let count = 0;
const verify=(condition, msg)=> { assert.ok(condition,msg); count++; };
verify(css.split(marker).length === 2,'one hotfix block only');
const rules = css.slice(css.indexOf('/* '+marker));
verify(rules.includes('@container siyayo-explorer (max-width:520px)'), 'mobile scoped');
verify(rules.includes('#dependencyHeadProbePanel .dependency-head-probe-prompt'), 'head prompt containment');
verify(rules.includes('#dependencyHeadProbePanel .dependency-head-probe-options>button'), 'head options minimum tap target');
verify(rules.includes('#pronounComparisonPanel>button.choice-audio'), 'audio grid column');
verify(rules.includes('#pronounComparisonPanel>button.gear-option'), 'pronoun choices grid');
verify(rules.includes('grid-template-columns:44px minmax(0,1fr) minmax(0,1fr)'), 'three columns: audio + 2 answers');
verify(rules.includes('min-height:44px'), 'native touch targets');
verify((rules.match(/\{/g)||[]).length===(rules.match(/\}/g)||[]).length, 'balanced css braces');
verify(comparison.includes("panel.id='pronounComparisonPanel'"), 'live panel id unchanged');
verify(comparison.includes("panel.className='dependency-head-probe-panel'"), 'same homologated frame');
verify(comparison.includes("audio.className='choice-audio'"), 'same audio button');
verify(comparison.includes("b.className='gear-option'"), 'same option buttons');
verify(comparison.includes("feedback.setAttribute('aria-live','polite')"), 'live feedback preserved');
verify(comparison.includes('evidenceProduced:false,greenPass:false'), 'pronoun diagnostic non-credit');
verify(headWire.includes('data-dependency-probe-audio'), 'head speech button unchanged');
verify(headWire.includes('data-dependency-head-probe-select'), 'head selection ids unchanged');
verify(!/submitObservedAttempt|evidenceProduced|greenPass|progression|passContract/i.test(rules),'CSS does not assert evidence authority');
console.log('PASS — '+count+' CSS/DOM integration invariants for ELO 7D.3.2');
