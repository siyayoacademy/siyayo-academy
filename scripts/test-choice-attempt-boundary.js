#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox=vm.createContext({});
sandbox.globalThis=sandbox;
vm.runInContext(fs.readFileSync('js/choice-attempt-ownership.js','utf8'),sandbox,{filename:'js/choice-attempt-ownership.js'});
vm.runInContext(fs.readFileSync('js/choice-attempt-boundary.js','utf8'),sandbox,{filename:'js/choice-attempt-boundary.js'});
const ownership=sandbox.SIYAYOChoiceAttemptOwnership;
const boundary=sandbox.SIYAYOChoiceAttemptBoundary;
assert(ownership&&boundary&&typeof boundary.assemble==='function');
const context=Object.freeze({currentExperienceId:'shopping-for-dinner',experienceLanguage:'en',experienceQuestion:'Which cheese should we choose?',experienceChoiceCandidate:'fresh-mild-cheese'});
const event=Object.freeze({observed:true,actor:'learner',source:'choice-select',occurrenceId:'choice-select:31',experienceId:'shopping-for-dinner',question:'Which cheese should we choose?',choice:'fresh-mild-cheese'});
const owner=ownership.contextFromChoice(event,context);
assert(owner,'grounded choice event should establish ownership');
const evidence=Object.freeze({dimension:'choice-function',result:'pass',context});
const support=Object.freeze({value:'audio',context});
const attempt=boundary.assemble({owner,evidence,support,context});
assert(attempt,'owned Choice evidence and contextual support should assemble a Choice Attempt');
assert.equal(attempt.occurrenceId,'choice-select:31');
assert.equal(attempt.dimension,'choice-function');
assert.equal(attempt.result,'pass');
assert.equal(attempt.support,'audio');
assert.equal('mode' in attempt,false,'Choice Attempt must not borrow sentence-built mode');
assert.equal(Object.isFrozen(attempt),true);
assert.equal(Object.isFrozen(attempt.context),true);
const sentenceEvidence=Object.freeze({dimension:'controlled-production',result:'pass',context});
assert.equal(boundary.assemble({owner,evidence:sentenceEvidence,support,context}),null,'sentence production evidence must not enter a Choice Attempt');
const es=Object.freeze({currentExperienceId:'shopping-for-dinner',experienceLanguage:'es',experienceQuestion:'Which cheese should we choose?',experienceChoiceCandidate:'fresh-mild-cheese'});
assert.equal(boundary.assemble({owner,evidence,support:Object.freeze({value:'audio',context:es}),context}),null,'mixed E/L/Q/C must fail closed');
assert.equal(boundary.assemble({owner,evidence,support:Object.freeze({occurrenceId:'choice-select:32',value:'audio',context}),context}),null,'conflicting explicit support occurrence must fail closed');
assert.equal(boundary.assemble({owner,evidence,support:null,context}),null,'missing support must fail closed');
console.log('Choice Attempt boundary: PASS — Choice footprint owns choice-function evidence plus contextual support without borrowing sentence-built mode.');
