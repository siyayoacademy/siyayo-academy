#!/usr/bin/env node
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
(async()=>{
const root={Object,Promise};root.globalThis=root;
function read(name){vm.runInNewContext(fs.readFileSync('js/'+name+'.js','utf8'),root);}
read('verb-explorer-learner-identity-source');
read('question-word-assessment-contract');
const names=['AdaptiveReadinessTrigger','AdaptiveLiveStart','CanonicalSkillLoader','ThinkingMindAssessmentSelection','AdaptiveCoordinator','AdaptiveProfileSource','AdaptiveEvidenceProfileSource','CanonicalSkillSource','PendingTransitionAuthority'];
const cleared=[];
for(const name of names)root['SIYAYOVerbExplorer'+name]={clear(){cleared.push(name);}};
root.SIYAYOLeafAssessmentTargetAuthority={clear(){cleared.push('target');}};
read('verb-explorer-learner-identity-provider');
const provider=root.SIYAYOVerbExplorerLearnerIdentityProvider,identity=root.SIYAYOVerbExplorerLearnerIdentitySource;
assert.equal(provider.provide(' First '),true);
assert.equal(identity.getId(),'First');
assert.equal(cleared.length,0,'first nick preserves only an explicit pending selection');
assert.equal(provider.provide('First'),true);
assert.equal(cleared.length,0,'same confirmed nick preserves progress');
assert.equal(provider.provide('Second'),true);
assert.equal(identity.getId(),'Second');
assert.equal(cleared.length,10,'new nick clears all learner-owned authorities');
assert.equal(provider.clear(),true);
assert.equal(identity.getId(),null,'anonymous exploration has no learner identity');
assert.equal(cleared.length,20);
let resolveFetch,adopted=0;
root.fetch=()=>new Promise(resolve=>{resolveFetch=resolve;});
root.SIYAYOVerbExplorerCanonicalSkillSource={adopt(){adopted++;return true;}};
read('verb-explorer-canonical-skill-loader');
const loader=root.SIYAYOVerbExplorerCanonicalSkillLoader;
const pending=loader.load('data/learning/skills/what.json');
loader.clear();
resolveFetch({ok:true,json:()=>Promise.resolve({id:'what.use.object-question'})});
assert.equal(await pending,false);
assert.equal(adopted,0,'late response cannot reactivate previous learner');
assert.equal(await loader.load('data/learning/skills/what.json'),true);
assert.equal(adopted,1,'new generation may reuse trusted definition');
let active={profile:{},session:{decision:{skill:'which.use.determiner',experienceId:'shopping-for-dinner'}},context:{evidencePackets:['observed']}};
let definition={id:'which.use.determiner'},selected=0;
identity.adopt('Second');
root.SIYAYOVerbExplorerAdaptiveStateBridge={getState:()=>({currentExperienceId:'shopping-for-dinner'})};
root.SIYAYOVerbExplorerAdaptiveCoordinator={snapshot:()=>active,clear(){active=null;}};
root.SIYAYOVerbExplorerCanonicalSkillSource={getDefinition:()=>definition,adopt(value){definition=value;return true;}};
root.SIYAYOVerbExplorerAdaptiveCoordinatorConfig={configure(input){active=input;return true;}};
root.SIYAYOLeafAssessmentTargetProvider={select(){selected++;return true;}};
read('verb-explorer-thinking-mind-assessment-selection');
const selection=root.SIYAYOVerbExplorerThinkingMindAssessmentSelection;
assert.equal(await selection.select({questionWord:'what'}),false,'no inferred skill');
assert.equal(await selection.select({assessmentTarget:{skill:'what.use.object-question',definitionPath:'what.json'}}),true);
assert.equal(selected,1);
assert.equal(await selection.select({assessmentTarget:{skill:'which.use.determiner',definitionPath:'which.json'}}),true);
assert.equal(active.context.evidencePackets[0],'observed','returning to skill preserves its contract progress');
selection.clear();active=null;
assert.equal(await selection.select({assessmentTarget:{skill:'which.use.determiner',definitionPath:'which.json'}}),true);
assert.equal(selected,2,'new learner cannot restore prior learner snapshot');
console.log('PASS — explicit nick replacement, anonymous reset and late-response isolation.');
})().catch(error=>{console.error(error);process.exit(1);});
